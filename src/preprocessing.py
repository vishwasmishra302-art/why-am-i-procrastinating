_MODEL_DIR      = "models"
_ENCODER_PATH   = os.path.join(_MODEL_DIR, "label_encoder.pkl")
_SCALER_PATH    = os.path.join(_MODEL_DIR, "scaler.pkl")
_IMPUTER_PATH   = os.path.join(_MODEL_DIR, "imputer.pkl")
_META_PATH      = os.path.join(_MODEL_DIR, "feature_meta.pkl")

#: Default dataset path (synthetic demo data).
_DEFAULT_DATA_PATH = os.path.join("data", "raw", "demo_dataset.csv")


# ══════════════════════════════════════════════════════════════════════════════
# Step 1 — Load dataset
# ══════════════════════════════════════════════════════════════════════════════

def load_dataset(path: str = _DEFAULT_DATA_PATH) -> pd.DataFrame:
    """
    Load a CSV dataset from disk.

    Accepts both the synthetic demo file (``data/raw/demo_dataset.csv``)
    and any real replacement dataset that shares the same schema.

    Parameters
    ----------
    path : str
        Absolute or relative path to the CSV file.

    Returns
    -------
    pd.DataFrame
        Raw dataframe as read from disk.

    Raises
    ------
    FileNotFoundError
        When the file does not exist at ``path``.
    """
    p = Path(path)
    if not p.exists():
        raise FileNotFoundError(
            f"\n[preprocessing] Dataset not found: '{path}'\n"
            "  → Generate the synthetic demo dataset first:\n"
            "      python -m src.data_generator\n"
            "  → Or supply a real CSV with the expected schema (see README)."
        )

    df = pd.read_csv(p)
    print(
        f"[preprocessing] Loaded  {len(df):,} rows × {len(df.columns)} cols"
        f"  from '{path}'"
    )
    return df


# ══════════════════════════════════════════════════════════════════════════════
# Step 2 — Schema validation
# ══════════════════════════════════════════════════════════════════════════════

def validate_schema(df: pd.DataFrame) -> None:
    """
    Assert that every required feature column and the target column exist.

    Parameters
    ----------
    df : pd.DataFrame
        Raw dataframe (as returned by ``load_dataset``).

    Raises
    ------
    ValueError
        Lists every missing column so the caller can fix all issues at once.
    """
    required = set(FEATURE_COLS) | {TARGET_COL}
    present  = set(df.columns)
    missing  = sorted(required - present)

    if missing:
        raise ValueError(
            f"\n[preprocessing] Schema validation FAILED.\n"
            f"  Missing columns : {missing}\n"
            f"  Found columns   : {sorted(present)}\n"
            "  Make sure the CSV was generated by src/data_generator.py or "
            "matches the documented schema (see README)."
        )

    # Warn if the data_source sentinel column is absent (real data may lack it)
    if "data_source" not in present:
        warnings.warn(
            "[preprocessing] Column 'data_source' not found.  "
            "If using real data, that is expected.  "
            "If using the demo file, regenerate it with src/data_generator.py.",
            UserWarning,
            stacklevel=2,
        )

    print("[preprocessing] Schema validation passed ✓")


# ══════════════════════════════════════════════════════════════════════════════
# Step 3 — Missing value detection
# ══════════════════════════════════════════════════════════════════════════════

def detect_missing_values(df: pd.DataFrame) -> dict[str, int]:
    """
    Scan the dataset for null / NaN values and report them.

    Only the required feature and target columns are inspected.
    Auxiliary columns (e.g. ``data_source``) are ignored.

    Parameters
    ----------
    df : pd.DataFrame

    Returns
    -------
    dict[str, int]
        Mapping ``{column_name: null_count}`` for columns that have at
        least one null.  Empty dict means no missing values.
    """
    cols_to_check = FEATURE_COLS + [TARGET_COL]
    null_counts   = df[cols_to_check].isnull().sum()
    missing       = null_counts[null_counts > 0].to_dict()

    if missing:
        total = sum(missing.values())
        print(
            f"[preprocessing] ⚠️  Missing values detected ({total} total):"
        )
        for col, count in missing.items():
            pct = 100.0 * count / len(df)
            print(f"    {col:<30} {count:>4} nulls  ({pct:.1f}%)")
    else:
        print("[preprocessing] No missing values detected ✓")

    return missing


# ══════════════════════════════════════════════════════════════════════════════
# Step 4 — Missing value handling
# ══════════════════════════════════════════════════════════════════════════════

def handle_missing_values(
    df: pd.DataFrame,
    imputer: Optional[SimpleImputer] = None,
    fit: bool = True,
) -> tuple[pd.DataFrame, SimpleImputer]:
    """
    Impute missing values in the numeric feature columns.

    Strategy: **median** imputation.  Median is preferred over mean for
    behavioural survey data because distributions are often skewed and the
    median is robust to outliers.

    ⚠️  Data-leakage rule: when called on the *test* split, pass the
    imputer fitted on the *training* split (``fit=False``).

    Parameters
    ----------
    df : pd.DataFrame
        Dataframe whose feature columns may contain nulls.
    imputer : SimpleImputer, optional
        Pre-fitted imputer.  Required when ``fit=False``.
    fit : bool
        If True, fit a new imputer on ``df``.
        If False, apply the supplied (already-fitted) imputer.

    Returns
    -------
    df_clean : pd.DataFrame
        Copy of ``df`` with nulls in feature columns replaced.
    imputer : SimpleImputer
        The fitted imputer (same object passed in when ``fit=False``).

    Raises
    ------
    ValueError
        If ``fit=False`` but no imputer is provided.
    """
    if not fit and imputer is None:
        raise ValueError(
            "[preprocessing] ``fit=False`` requires a pre-fitted imputer to be supplied."
            " Pass the imputer returned when fit=True on the training split."
        )

    df_clean = df.copy()

    if fit:
        imputer = SimpleImputer(strategy="median")
        imputer.fit(df_clean[FEATURE_COLS])
        print("[preprocessing] SimpleImputer(strategy='median') fitted on training data.")

    # Replace feature columns only; leave target unchanged
    df_clean[FEATURE_COLS] = imputer.transform(df_clean[FEATURE_COLS])

    remaining_nulls = df_clean[FEATURE_COLS].isnull().sum().sum()
    if remaining_nulls > 0:
        warnings.warn(
            f"[preprocessing] {remaining_nulls} null(s) remain after imputation. "
            "This should not happen with SimpleImputer — check for non-numeric values.",
            UserWarning,
            stacklevel=2,
        )
    else:
        print("[preprocessing] Imputation complete — 0 nulls remain ✓")

    return df_clean, imputer


# ══════════════════════════════════════════════════════════════════════════════
# Step 5 — Feature range validation
# ══════════════════════════════════════════════════════════════════════════════

def validate_feature_ranges(df: pd.DataFrame) -> pd.DataFrame:
    """
    Check each numeric feature against its documented valid range and
    clip any out-of-bounds values.

    Clipping rather than dropping is chosen so no rows are silently
    discarded.  A warning is logged for every affected column so the
    data owner is aware of anomalous inputs.

    Parameters
    ----------
    df : pd.DataFrame

    Returns
    -------
    pd.DataFrame
        Copy of ``df`` with all feature values within valid bounds.
    """
    df_checked = df.copy()
    any_clipped = False

    for feat, (lo, hi) in FEATURE_RANGES.items():
        if feat not in df_checked.columns:
            continue

        col      = df_checked[feat]
        n_low    = int((col < lo).sum())
        n_high   = int((col > hi).sum())
        n_oob    = n_low + n_high

        if n_oob > 0:
            any_clipped = True
            warnings.warn(
                f"[preprocessing] '{feat}': {n_oob} value(s) outside valid range "
                f"[{lo}, {hi}]  ({n_low} below, {n_high} above).  Clipping.",
                UserWarning,
                stacklevel=2,
            )
            df_checked[feat] = col.clip(lo, hi)

    if not any_clipped:
        print("[preprocessing] All feature values within valid ranges ✓")
    else:
        print("[preprocessing] Out-of-range values clipped ✓")

    return df_checked


# ══════════════════════════════════════════════════════════════════════════════
# Step 6 — Feature / target separation
# ══════════════════════════════════════════════════════════════════════════════

def split_features_target(
    df: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.Series]:
    """
    Separate the feature matrix (X) from the target column (y).

    Only the columns listed in ``FEATURE_COLS`` are returned as X.
    Any extra columns (e.g. ``data_source``) are silently dropped.

    Parameters
    ----------
    df : pd.DataFrame

    Returns
    -------
    X : pd.DataFrame
        Feature matrix with columns in the canonical ``FEATURE_COLS`` order.
    y_raw : pd.Series
        Raw string labels (not yet encoded).
    """
    X     = df[FEATURE_COLS].copy().astype(np.float32)
    y_raw = df[TARGET_COL].copy()

    print(
        f"[preprocessing] Features : {X.shape[1]} cols × {X.shape[0]:,} rows"
        f"  |  Target : '{TARGET_COL}'"
    )
    return X, y_raw


# ══════════════════════════════════════════════════════════════════════════════
# Step 7 — Target encoding
# ══════════════════════════════════════════════════════════════════════════════

def encode_target(
    y_raw: pd.Series,
    label_encoder: Optional[LabelEncoder] = None,
    fit: bool = True,
) -> tuple[np.ndarray, LabelEncoder]:
    """
    Encode the string target labels as integers using a ``LabelEncoder``.

    The encoded integers correspond to alphabetical order of the class names
    (sklearn default).  Use ``label_encoder.inverse_transform`` to convert
    back to human-readable labels.

    ⚠️  Data-leakage rule: the encoder must always be fitted on the **full**
    raw label set (before splitting) so that all classes are known.  Pass
    ``fit=False`` only when applying an already-fitted encoder to a subset.

    Parameters
    ----------
    y_raw : pd.Series
        String target labels.
    label_encoder : LabelEncoder, optional
        Pre-fitted encoder (required when ``fit=False``).
    fit : bool
        If True, fit a new LabelEncoder on ``y_raw``.

    Returns
    -------
    y : np.ndarray
        Integer-encoded labels, shape (n_samples,).
    label_encoder : LabelEncoder
        Fitted encoder.

    Raises
    ------
    ValueError
        If ``fit=False`` but no encoder is supplied, or if any label in
        ``y_raw`` is unseen by the fitted encoder.
    """
    if not fit and label_encoder is None:
        raise ValueError(
            "[preprocessing] ``fit=False`` requires a pre-fitted LabelEncoder."
        )

    if fit:
        label_encoder = LabelEncoder()
        label_encoder.fit(y_raw)

    # Detect unseen labels before transforming (gives a clear error message)
    known   = set(label_encoder.classes_)
    present = set(y_raw.unique())
    unseen  = present - known
    if unseen:
        raise ValueError(
            f"[preprocessing] Target column contains unseen class labels: {unseen}\n"
            f"  Known classes: {sorted(known)}"
        )

    y = label_encoder.transform(y_raw)
    print(f"[preprocessing] Classes ({len(label_encoder.classes_)}): "
          f"{list(label_encoder.classes_)}")
    return y, label_encoder


# ══════════════════════════════════════════════════════════════════════════════
# Step 8 — Train / test split (stratified)
# ══════════════════════════════════════════════════════════════════════════════

def split_train_test(
    X: pd.DataFrame,
    y: np.ndarray,
    test_size: float = 0.20,
    random_state: int = 42,
) -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """
    Perform a stratified train / test split.

    Stratification ensures each class is proportionally represented in
    both splits — essential for multi-class problems with class imbalance.

    No preprocessing transformation is applied here; that happens
    *after* the split to prevent data leakage.

    Parameters
    ----------
    X : pd.DataFrame
        Feature matrix (will be converted to np.ndarray).
    y : np.ndarray
        Integer-encoded target labels.
    test_size : float
        Fraction of data held out for evaluation (default 0.20 = 20%).
    random_state : int
        Seed for reproducibility.

    Returns
    -------
    X_train, X_test : np.ndarray   shape (n_train, 12), (n_test, 12)
    y_train, y_test : np.ndarray   shape (n_train,), (n_test,)

    Raises
    ------
    ValueError
        If ``test_size`` is not in (0, 1) or if any class has fewer than
        2 samples (stratification requires at least 1 per split).
    """
    if not 0.0 < test_size < 1.0:
        raise ValueError(
            f"[preprocessing] test_size must be between 0 and 1, got {test_size}."
        )

    X_arr = X.values if isinstance(X, pd.DataFrame) else X

    X_train, X_test, y_train, y_test = train_test_split(
        X_arr,
        y,
        test_size=test_size,
        random_state=random_state,
        stratify=y,   # ← critical for multi-class balance
    )

    n_total = len(y)
    print(
        f"[preprocessing] Split  → Train: {len(y_train):,} ({100*(1-test_size):.0f}%)"
        f"  |  Test: {len(y_test):,} ({100*test_size:.0f}%)"
        f"  |  Total: {n_total:,}"
    )

    # Verify stratification produced proportional class distributions
    unique_train, counts_train = np.unique(y_train, return_counts=True)
    unique_test,  counts_test  = np.unique(y_test,  return_counts=True)
    if len(unique_train) != len(unique_test):
        warnings.warn(
            "[preprocessing] Train and test sets have different numbers of unique "
            "classes after stratified split.  This may indicate very small classes.",
            UserWarning,
            stacklevel=2,
        )

    return X_train, X_test, y_train, y_test


# ══════════════════════════════════════════════════════════════════════════════
# Steps 9 & 10 — Scaler fitting and transformation
# ══════════════════════════════════════════════════════════════════════════════

def fit_scaler(X_train: np.ndarray) -> StandardScaler:
    """
    Fit a ``StandardScaler`` **exclusively** on the training set.

    StandardScaler is used to normalise features for Logistic Regression.
    Tree-based models (Random Forest, XGBoost) use the raw (unscaled) features
    because they are scale-invariant.

    ⚠️  Data-leakage rule: this function MUST be called with training data only.
    Never pass the test set or the full dataset here.

    Parameters
    ----------
    X_train : np.ndarray
        Raw training feature matrix, shape (n_train, n_features).

    Returns
    -------
    StandardScaler
        Fitted scaler.  Call ``.transform(X_test)`` to apply it to the test set.
    """
    scaler = StandardScaler()
    scaler.fit(X_train)
    print(
        "[preprocessing] StandardScaler fitted on training data only ✓"
        f"  (means: {scaler.mean_.round(2)[:3]}…)"
    )
    return scaler


def transform_features(
    X: np.ndarray,
    scaler: StandardScaler,
) -> np.ndarray:
    """
    Apply a **pre-fitted** scaler to a feature matrix.

    Works identically for the training split and the test split — the
    only difference is whether ``scaler`` was fitted on this data or not.
    (It should only have been fitted on the training split.)

    Parameters
    ----------
    X : np.ndarray
        Raw feature matrix of any split.
    scaler : StandardScaler
        Pre-fitted scaler (from ``fit_scaler``).

    Returns
    -------
    np.ndarray
        Scaled feature matrix, same shape as ``X``.
    """
    return scaler.transform(X)


# ══════════════════════════════════════════════════════════════════════════════
# Inference helper — Streamlit single-sample transformation
# ══════════════════════════════════════════════════════════════════════════════

def transform_input_for_inference(
    input_dict: dict[str, float],
    scaler: StandardScaler,
    imputer: SimpleImputer,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Transform a single user-supplied input dictionary into feature arrays
    ready for model inference.

    This function applies **exactly the same** transformations as the
    training pipeline (imputation → range clipping → scaling), ensuring
    that a live Streamlit input is processed identically to training data.

    Parameters
    ----------
    input_dict : dict[str, float]
        Mapping ``{feature_name: value}`` for all 12 features, as collected
        from the Streamlit slider widgets.
    scaler : StandardScaler
        Fitted scaler loaded from ``models/scaler.pkl``.
    imputer : SimpleImputer
        Fitted imputer loaded from ``models/imputer.pkl``.

    Returns
    -------
    X_raw : np.ndarray, shape (1, 12)
        Unscaled feature vector (for Random Forest / XGBoost).
    X_scaled : np.ndarray, shape (1, 12)
        StandardScaler-normalised feature vector (for Logistic Regression).

    Raises
    ------
    KeyError
        If any required feature is absent from ``input_dict``.
    ValueError
        If any feature value is not finite (NaN, ±inf).
    """
    # ── Validate keys ──────────────────────────────────────────────────────────
    missing_keys = [f for f in FEATURE_COLS if f not in input_dict]
    if missing_keys:
        raise KeyError(
            f"[inference] Missing features in input: {missing_keys}\n"
            f"  Required: {FEATURE_COLS}"
        )

    # ── Build ordered row ──────────────────────────────────────────────────────
    row = np.array([[input_dict[f] for f in FEATURE_COLS]], dtype=np.float64)

    # ── Validate finite values ─────────────────────────────────────────────────
    if not np.all(np.isfinite(row)):
        bad = [FEATURE_COLS[i] for i in range(len(FEATURE_COLS))
               if not np.isfinite(row[0, i])]
        raise ValueError(
            f"[inference] Non-finite value(s) detected in input: {bad}"
        )

    # ── Impute (handles any NaN from future API changes) ──────────────────────
    # Pass as DataFrame so scikit-learn's imputer recognises feature names and
    # does not emit "X does not have valid feature names" UserWarning at runtime.
    import pandas as _pd
    row_df = _pd.DataFrame(row, columns=FEATURE_COLS)
    row = imputer.transform(row_df)

    # ── Clip to valid ranges ───────────────────────────────────────────────────
    for i, feat in enumerate(FEATURE_COLS):
        lo, hi    = FEATURE_RANGES[feat]
        row[0, i] = float(np.clip(row[0, i], lo, hi))

    X_raw    = row.astype(np.float32)
    X_scaled = scaler.transform(row).astype(np.float32)

    return X_raw, X_scaled


# ══════════════════════════════════════════════════════════════════════════════
# Persistence helpers
# ══════════════════════════════════════════════════════════════════════════════

def save_preprocessing_artefacts(
    label_encoder: LabelEncoder,
    scaler: StandardScaler,
    imputer: SimpleImputer,
) -> None:
    """
    Persist all fitted preprocessing objects to the ``models/`` directory.

    Saved files
    -----------
    ``models/label_encoder.pkl`` — LabelEncoder (target ↔ integer mapping)
    ``models/scaler.pkl``        — StandardScaler (fitted on X_train only)
    ``models/imputer.pkl``       — SimpleImputer  (fitted on X_train only)
    ``models/feature_meta.pkl``  — dict with feature names and valid ranges

    Parameters
    ----------
    label_encoder : LabelEncoder
    scaler : StandardScaler
    imputer : SimpleImputer
    """
    os.makedirs(_MODEL_DIR, exist_ok=True)

    joblib.dump(label_encoder, _ENCODER_PATH)
    joblib.dump(scaler,        _SCALER_PATH)
    joblib.dump(imputer,       _IMPUTER_PATH)

    # Feature metadata — used at inference time to validate and clip inputs
    feature_meta = {
        "feature_cols":    FEATURE_COLS,
        "feature_ranges":  FEATURE_RANGES,
        "class_labels":    CLASS_LABELS,
        "target_col":      TARGET_COL,
    }
    joblib.dump(feature_meta, _META_PATH)

    print("[preprocessing] Artefacts saved:")
    for path in [_ENCODER_PATH, _SCALER_PATH, _IMPUTER_PATH, _META_PATH]:
        size_kb = os.path.getsize(path) / 1024
        print(f"    {path}  ({size_kb:.1f} KB)")


def load_preprocessing_artefacts() -> dict:
    """
    Load all saved preprocessing artefacts from ``models/``.

    Used by ``src/predict.py`` (and ``app.py``) to process live Streamlit
    inputs using the exact same transformations applied during training.

    Returns
    -------
    dict with keys:
        ``label_encoder`` — LabelEncoder
        ``scaler``        — StandardScaler
        ``imputer``       — SimpleImputer
        ``feature_meta``  — dict (feature names + ranges)

    Raises
    ------
    FileNotFoundError
        If any required artefact file is missing.
    """
    required = {
        "label_encoder": _ENCODER_PATH,
        "scaler":        _SCALER_PATH,
        "imputer":       _IMPUTER_PATH,
        "feature_meta":  _META_PATH,
    }
    missing = [p for p in required.values() if not os.path.exists(p)]
    if missing:
        raise FileNotFoundError(
            "[preprocessing] The following artefact files are missing:\n"
            + "\n".join(f"  {p}" for p in missing)
            + "\n\nRun the preprocessing pipeline first:\n"
            "  python -m src.preprocessing"
        )

    return {
        "label_encoder": joblib.load(_ENCODER_PATH),
        "scaler":        joblib.load(_SCALER_PATH),
        "imputer":       joblib.load(_IMPUTER_PATH),
        "feature_meta":  joblib.load(_META_PATH),
    }


# ══════════════════════════════════════════════════════════════════════════════
# Step 12 — Pipeline orchestrator
# ══════════════════════════════════════════════════════════════════════════════

def build_pipeline(
    path: str = _DEFAULT_DATA_PATH,
    test_size: float = 0.20,
    random_seed: int = 42,
) -> dict:
    """
    Run the complete preprocessing pipeline end-to-end.

    Sequentially executes all 11 preprocessing steps, enforcing
    the no-data-leakage rule: every transformer is fitted on the
    training split only and then applied to the test split.

    Parameters
    ----------
    path : str
        Path to the input CSV (defaults to the synthetic demo dataset).
    test_size : float
        Fraction of samples held out for testing (default 0.20).
    random_seed : int
        Random seed for the train/test split (default 42).

    Returns
    -------
    dict
        All data splits and fitted objects, with keys:

        Data arrays
        ~~~~~~~~~~~
        ``X_train``     np.ndarray  (n_train, 12) — raw features, training
        ``X_test``      np.ndarray  (n_test,  12) — raw features, test
        ``X_train_sc``  np.ndarray  (n_train, 12) — scaled features, training
        ``X_test_sc``   np.ndarray  (n_test,  12) — scaled features, test
        ``y_train``     np.ndarray  (n_train,)    — encoded labels, training
        ``y_test``      np.ndarray  (n_test,)     — encoded labels, test

        Fitted objects
        ~~~~~~~~~~~~~~
        ``label_encoder``  LabelEncoder   — target ↔ integer mapping
        ``scaler``         StandardScaler — fitted on X_train only
        ``imputer``        SimpleImputer  — fitted on X_train only

        Metadata
        ~~~~~~~~
        ``feature_names``  list[str]  — canonical feature column order
        ``class_names``    list[str]  — human-readable class labels

    Notes
    -----
    * All four sklearn objects are also persisted to ``models/``.
    * To use real data, replace ``path`` with the path to your CSV.
      The CSV must contain all columns listed in ``FEATURE_COLS`` plus
      ``procrastination_reason``.

    ⚠️  The default path points to the synthetic demo dataset.
        Do NOT use demo-data results as real findings.
    """
    print("\n" + "=" * 60)
    print("  PREPROCESSING PIPELINE")
    print("=" * 60)

    # ── Step 1: Load ───────────────────────────────────────────────────────────
    df = load_dataset(path)

    # ── Step 2: Schema validation ──────────────────────────────────────────────
    validate_schema(df)

    # ── Step 3: Detect missing values ──────────────────────────────────────────
    detect_missing_values(df)

    # ── Step 4 & 5 will happen after split (to avoid leakage) — see below ──

    # ── Step 5 (pre-split): Range validation on the full frame ─────────────────
    # Clipping uses only domain knowledge (hard-coded ranges), not data statistics,
    # so it is safe to apply before the split.
    df = validate_feature_ranges(df)

    # ── Step 6: Separate features and target ───────────────────────────────────
    X, y_raw = split_features_target(df)

    # ── Step 7: Encode target (on full y_raw so all classes are seen) ──────────
    y, label_encoder = encode_target(y_raw, fit=True)

    # ── Step 8: Stratified train / test split ──────────────────────────────────
    X_train, X_test, y_train, y_test = split_train_test(
        X, y, test_size=test_size, random_state=random_seed
    )

    # ── Step 4 (post-split): Fit imputer on training data only ─────────────────
    # Convert splits back to DataFrames for the imputer (needs column names)
    X_train_df = pd.DataFrame(X_train, columns=FEATURE_COLS)
    X_test_df  = pd.DataFrame(X_test,  columns=FEATURE_COLS)

    X_train_df, imputer = handle_missing_values(X_train_df, fit=True)
    X_test_df,  _       = handle_missing_values(X_test_df, imputer=imputer, fit=False)

    X_train = X_train_df.values.astype(np.float32)
    X_test  = X_test_df.values.astype(np.float32)

    # ── Step 9: Fit scaler on training data only ───────────────────────────────
    scaler = fit_scaler(X_train)

    # ── Step 10: Transform both splits ────────────────────────────────────────
    X_train_sc = transform_features(X_train, scaler)
    X_test_sc  = transform_features(X_test,  scaler)

    # ── Step 11: Persist all artefacts ────────────────────────────────────────
    save_preprocessing_artefacts(label_encoder, scaler, imputer)

    print("\n[preprocessing] ✅ Pipeline complete.")
    print("=" * 60 + "\n")

    return {
        # Data arrays
        "X_train":       X_train,
        "X_test":        X_test,
        "X_train_sc":    X_train_sc,
        "X_test_sc":     X_test_sc,
        "y_train":       y_train,
        "y_test":        y_test,
        # Fitted objects
        "label_encoder": label_encoder,
        "scaler":        scaler,
        "imputer":       imputer,
        # Metadata
        "feature_names": FEATURE_COLS,
        "class_names":   list(label_encoder.classes_),
    }


